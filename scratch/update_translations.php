foreach ($locales as $loc) {
    $filePath = __DIR__ . '/../lang/' . $loc . '/messages.php';
    if (!file_exists($filePath)) {
        echo "File not found: $filePath\n";
        continue;
    }

    $content = file_get_contents($filePath);
    $lastBracketPos = strrpos($content, '];');
    if ($lastBracketPos === false) {
        echo "Could not find closing bracket in $filePath\n";
        continue;
    }

    $appendLines = "\n    // --- 7S 2.0 Module Translations ---\n";
    foreach ($translations[$loc] as $key => $val) {
        $escapedVal = addcslashes($val, "'\\");
        $appendLines .= "    '{$key}' => '{$escapedVal}',\n";
    }

    $newContent = substr($content, 0, $lastBracketPos) . $appendLines . substr($content, $lastBracketPos);
    file_put_contents($filePath, $newContent);
    echo "Updated $loc successfully.\n";
}
